import sys
sys.path.insert(0,(__import__("pathlib").Path(__file__).resolve().parents[5].as_posix() + "/design/ecad/case/pcb"))
import pcbnew
from pcbnew import FromMM as mm
b=pcbnew.BOARD()
print('a',flush=True)
b.SetCopperLayerCount(4)
ds=b.GetDesignSettings()
print('b',flush=True)
ds.SetBoardThickness(mm(1.0)); print('c',flush=True)
ds.m_TrackMinWidth=mm(0.15); print('d',flush=True)
ds.m_MinClearance=mm(0.15); print('e',flush=True)
ds.m_ViasMinSize=mm(0.6); print('f',flush=True)
ds.m_ViasMinAnnulus=mm(0.15); print('g',flush=True)
ds.m_MinThroughDrill=mm(0.3); print('h',flush=True)
ds.m_CopperEdgeClearance=mm(0.2); print('i',flush=True)
ds.m_HoleToHoleMin=mm(0.25); print('j',flush=True)
ds.m_HoleClearance=mm(0.15); print('k',flush=True)
ds.m_MinSilkClearance=mm(0.15); print('l',flush=True)
ds.m_SolderMaskMinWidth=mm(0.1); print('m',flush=True)
ds.m_SolderMaskExpansion=mm(0.05); print('n',flush=True)
ds.m_SolderMaskToCopperClearance=mm(0.05); print('o',flush=True)
ds.m_MinResolvedSpokes=2; print('p',flush=True)
ds.m_MinConn=mm(0.15); print('q',flush=True)
ns=ds.m_NetSettings
dc=ns.GetDefaultNetclass(); print('r',flush=True)
dc.SetClearance(mm(0.15)); dc.SetTrackWidth(mm(0.15)); dc.SetViaDiameter(mm(0.6)); dc.SetViaDrill(mm(0.3)); print('s',flush=True)
dc.SetDiffPairWidth(mm(0.15)); dc.SetDiffPairGap(mm(0.15)); print('t',flush=True)
nc=pcbnew.NETCLASS('pwr'); print('u',flush=True)
nc.SetClearance(mm(0.15)); nc.SetTrackWidth(mm(0.4)); print('v',flush=True)
ns.SetNetclass('pwr',nc); print('w',flush=True)
ns.SetNetclassPatternAssignment('SYS','pwr'); print('x',flush=True)
