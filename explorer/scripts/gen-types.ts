// Makes src/contract/records.ts from contract/schema/*.schema.json. The schema is the single source;
// the types are derived. `--check` fails when the committed file differs from a fresh run.
import { compileFromFile } from 'json-schema-to-typescript'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const schemaDir = join(root, 'contract', 'schema')
const outFile = join(root, 'src', 'contract', 'records.ts')
const registry = JSON.parse(readFileSync(join(schemaDir, 'records.json'), 'utf8')) as {
  records: { id: string; schema: string }[]
  manifest: { schema: string }
  content: { schema: string }[]
}

const names = [
  'common',
  ...registry.records.map((r) => r.schema),
  registry.manifest.schema,
  ...registry.content.map((c) => c.schema),
]

const seen = new Set<string>()
const chunks: string[] = []
for (const n of names) {
  const file = join(schemaDir, `${n}.schema.json`)
  const ts = await compileFromFile(file, {
    bannerComment: '',
    cwd: dirname(file),
    declareExternallyReferenced: true,
    additionalProperties: false,
    format: false,
    unreachableDefinitions: n === 'common',
  })
  // split into top-level declarations; keep the first copy of each name
  const parts = ts.replace(/\bSource\d+\b/g, 'Source').split(/\n(?=(?:\/\*\*(?:(?!\*\/)[\s\S])*\*\/\n)?export (?:interface|type) )/)
  for (const part of parts) {
    const m = /export (?:interface|type) (\w+)/.exec(part)
    const name = m?.[1]
    if (!name || name === 'Common' || seen.has(name)) continue
    seen.add(name)
    chunks.push(part.trim())
  }
}

const header = `// GENERATED by scripts/gen-types.ts from contract/schema/*.schema.json. Do not edit by hand.\n// Change the schema, then run: npm run gen:types\n\n`
const body = header + chunks.join('\n\n') + '\n'

if (process.argv.includes('--check')) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : ''
  if (current !== body) {
    console.error('src/contract/records.ts is out of date with contract/schema. Run: npm run gen:types')
    process.exit(1)
  }
  console.log(`types fresh: ${seen.size} declarations`)
} else {
  writeFileSync(outFile, body)
  console.log(`wrote src/contract/records.ts (${seen.size} declarations)`)
}
