"""Writes tests/sys/src/crash_expect.h: the stored crash block as bytes typed from the layout of design/firmware.md l.1063
(reason u32, PC u32, LR u32, PSR u32, thread name 16 bytes, 64 stack words, little-endian), with this unit's magic "CRSH"
in front and the CRC-32 (zlib, ISO-HDLC) of the 292 bytes before it at the end. Independent of the code under test."""
import struct, sys, zlib
reason, pc, lr, psr = 4, 0x0001A2B4, 0x0001A2B5, 0x61000000
name = b"audio".ljust(16, b"\0")
stack = [0xA5000000 + i for i in range(64)]
blk = struct.pack("<IIII", reason, pc, lr, psr) + name + b"".join(struct.pack("<I", w) for w in stack)
assert len(blk) == 288
body = b"CRSH" + blk
raw = body + struct.pack("<I", zlib.crc32(body))
assert len(raw) == 296
out = ["/* generated by build-logs/step6/u7-gen-crash-expect.py: the stored crash block for reason 4, pc 0x0001A2B4,",
       " * lr 0x0001A2B5, psr 0x61000000, thread \"audio\", stack word i = 0xA5000000 + i. CRC-32 over bytes 0..291: 0x%08X */" % zlib.crc32(body),
       "static const uint8_t crash_expect[296] = {"]
for i in range(0, 296, 12):
    out.append("\t" + ", ".join("0x%02X" % b for b in raw[i:i+12]) + ",")
out.append("};")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
print("crc32 0x%08X" % zlib.crc32(body))
